import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('./',import.meta.url);
const hashed=(name,content)=>name.replace('.js','').replace('.css','')+'.'+createHash('sha256').update(content).digest('hex').slice(0,12)+(name.endsWith('.css')?'.css':'.js');
await mkdir(new URL('assets/',root),{recursive:true});
const cosmos=await readFile(new URL('cosmos.js',root),'utf8'),cosmosName=hashed('cosmos.js',cosmos);
const battle=await readFile(new URL('battle.js',root),'utf8'),battleName=hashed('battle.js',battle);
const app=(await readFile(new URL('app.js',root),'utf8')).replace("'./cosmos.js'",`'./${cosmosName}'`).replace("'./battle.js'",`'./${battleName}'`),appName=hashed('app.js',app);
const css=await readFile(new URL('style.css',root),'utf8'),cssName=hashed('style.css',css);
for(const [name,content] of [[cosmosName,cosmos],[battleName,battle],[appName,app],[cssName,css]])await writeFile(new URL('assets/'+name,root),content);
let html=await readFile(new URL('index.html',root),'utf8');
html=html.replace(/href="\.\/(?:assets\/)?style(?:\.[a-f0-9]+)?\.css"/,`href="./assets/${cssName}"`).replace(/src="\.\/(?:assets\/)?app(?:\.[a-f0-9]+)?\.js"/,`src="./assets/${appName}"`);
await writeFile(new URL('index.html',root),html);
console.log('已生成版本独立的样式、脚本和场景文件');
